package co.klei.core.audit

/** The closed catalogue of Audit Entry actions (FR-40). The stored value is [code]; the screen maps it to a label and shows an unknown code as-is. */
enum class AuditAction {
    SIGN_IN_LOCKED, SIGN_IN_NO_ACCESS, REFRESH_REUSE, FORBIDDEN,
    BOOTSTRAP_ADMIN, USER_INVITED, USER_INVITE_RESENT, USER_UPDATED, USER_ROLE_CHANGED, USER_DELETED,
    EMAIL_VERIFIED, PASSWORD_RESET, PASSWORD_CHANGED, ROLE_PERMISSIONS_CHANGED,
    AI_SETTINGS_CHANGED, TAXONOMY_CHANGED, UPLOAD_SAVED, UPLOAD_DISCARDED, GOWN_EDITED, GOWN_DELETED,
    INQUIRY_STATUS_CHANGED, REPLY_SENT, KEY_ROTATION, AWAY_CHANGED,
    TWOFA_ENABLED, TWOFA_DISABLED, TWOFA_RESET, SIGN_IN_TWOFA_FAILED;

    val code: String get() = name.lowercase()
}
