#!/usr/bin/env node
// Generates the Auth Web token sheet from DESIGN.md (UX-DR1). `--check` fails when the committed file is stale.
// shortcut: reads only the colors/typography/rounded/spacing maps (two-level nesting at most); add a YAML parser if DESIGN.md grows deeper maps.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const src = resolve(root, 'docs/planning-artifacts/ux-designs/ux-klei-bridal-dashboard-2026-11-08/DESIGN.md')
const out = resolve(root, 'backend/app/src/main/resources/static/tokens.css')

export function parse(text) {
  const fm = text.split(/^---$/m)[1]
  const tree = {}
  const stack = [{ indent: -1, node: tree }]
  for (const line of fm.split('\n')) {
    const m = line.match(/^( *)([^\s:][^:]*):\s*(.*)$/)
    if (!m) continue
    const indent = m[1].length
    const key = m[2].replace(/^['"]|['"]$/g, '')
    while (stack.at(-1).indent >= indent) stack.pop()
    const parent = stack.at(-1).node
    if (m[3] === '') { parent[key] = {}; stack.push({ indent, node: parent[key] }) }
    else parent[key] = m[3].replace(/^['"]|['"]$/g, '')
  }
  return tree
}

// shortcut: Inter files are fixed (latin only, weights the UI uses); relative URLs resolve beside tokens.css for Auth Web and, through the Vite @import, for the desktop.
const faces = [400, 500, 600, 700].map((w) => `@font-face { font-family: Inter; font-weight: ${w}; font-display: swap; src: url('fonts/inter-latin-${w}.woff2') format('woff2'); }`)

export function css(t) {
  const lines = [':root {']
  for (const [k, v] of Object.entries(t.colors)) lines.push(`  --color-${k}: ${v};`)
  for (const [k, v] of Object.entries(t.rounded)) lines.push(`  --radius-${k}: ${v};`)
  for (const [k, v] of Object.entries(t.elevation ?? {})) lines.push(`  --elev-${k}: ${v};`)
  for (const [k, v] of Object.entries(t.spacing)) lines.push(`  --space-${k}: ${v};`)
  for (const [k, v] of Object.entries(t.typography)) {
    for (const [p, val] of Object.entries(v)) lines.push(`  --type-${k}-${p.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase())}: ${val};`)
  }
  lines.push('}')
  return '/* Generated by infra/ci/gen-tokens.mjs from DESIGN.md. Do not edit. */\n' + faces.join('\n') + '\n' + lines.join('\n') + '\n'
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = css(parse(readFileSync(src, 'utf8')))
  if (process.argv.includes('--check')) {
    let cur = ''
    try { cur = readFileSync(out, 'utf8') } catch {}
    if (cur !== next) { console.error('tokens.css is stale: run node infra/ci/gen-tokens.mjs'); process.exit(1) }
  } else writeFileSync(out, next)
}
